"""Export a simulated network to LAMMPS for the second-stage, viscoelastic (dynamic) model.

The quasi-static solver in network.py gives equilibrium moduli and rupture.  LAMMPS adds what it
cannot: inertia, solvent drag (Langevin), and oscillatory shear -> storage/loss moduli G', G''.

Mapping (LAMMPS harmonic styles use E = K (x - x0)^2, so K = stiffness / 2):
  bond type 1..n  collagen segments (one type per distinct mu)  K = mu/2, r0 = 1
  bond type last  elastin (every lattice bond)                  K = mu_el/2
  angle type 1    fibre bending, theta0 = 180                   K = kappa/2 (per-pair factor binned)
  angle type 2    locked oxidative junction, theta0 = 60        K = kx/2
  fix spring/self GAG embedding                                  K = k_gag
Units: lj, 2D, triclinic periodic box tilted by fix deform for shear.
"""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np

from .network import Lattice, SystemSpec


def export(spec: SystemSpec, lat: Lattice, out_dir: Path, name="network", gamma0=0.02, period=200.0,
           cycles=5, damp=1.0, temp=1e-6):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    X = lat.X
    alive = spec.alive
    mus = np.round(spec.mu[alive], 6)
    mu_types = {m: i + 1 for i, m in enumerate(sorted(set(mus.tolist())))}
    n_col_types = len(mu_types)
    bonds = []
    for b in np.flatnonzero(alive):
        bonds.append((mu_types[round(float(spec.mu[b]), 6)], lat.bi[b] + 1, lat.bj[b] + 1))
    if spec.mu_el > 0:
        for b in range(lat.Nb):
            bonds.append((n_col_types + 1, lat.bi[b] + 1, lat.bj[b] + 1))
    n_bond_types = n_col_types + (1 if spec.mu_el > 0 else 0)

    angles = []
    for p in range(len(lat.bend_in)):
        bi, bo = lat.bend_in[p], lat.bend_out[p]
        if alive[bi] and alive[bo]:
            angles.append((1, lat.bi[bi] + 1, lat.bend_node[p] + 1, lat.bj[bo] + 1))
    for q in range(len(lat.ang_u)):
        n = lat.ang_node[q]
        if spec.rigid_node[n] > 0 and alive[lat.ang_u[q]] and alive[lat.ang_v[q]]:
            u, v = lat.ang_u[q], lat.ang_v[q]
            a_end = lat.bj[u] if lat.ang_su[q] > 0 else lat.bi[u]
            c_end = lat.bj[v] if lat.ang_sv[q] > 0 else lat.bi[v]
            angles.append((2, a_end + 1, n + 1, c_end + 1))

    Lx, Ly = lat.L
    lines = [f"LAMMPS data file: {name} {spec.meta}", "",
             f"{lat.N} atoms", f"{len(bonds)} bonds", f"{len(angles)} angles", "",
             "1 atom types", f"{n_bond_types} bond types", "2 angle types", "",
             f"0 {Lx} xlo xhi", f"0 {Ly} ylo yhi", "-0.5 0.5 zlo zhi", "0 0 0 xy xz yz", "",
             "Masses", "", "1 1.0", "", "Atoms # molecular", ""]
    lines += [f"{i + 1} 1 1 {X[i, 0]:.8f} {X[i, 1]:.8f} 0.0" for i in range(lat.N)]
    lines += ["", "Bonds", ""] + [f"{k + 1} {t} {i} {j}" for k, (t, i, j) in enumerate(bonds)]
    lines += ["", "Angles", ""] + [f"{k + 1} {t} {i} {j} {l}" for k, (t, i, j, l) in enumerate(angles)]
    (out_dir / f"{name}.data").write_text("\n".join(lines) + "\n")

    kx = float(spec.rigid_node.max()) if spec.rigid_node.max() > 0 else 0.0
    coeffs = [f"bond_coeff {t} {m / 2:.8g} 1.0" for m, t in mu_types.items()]
    if spec.mu_el > 0:
        coeffs.append(f"bond_coeff {n_col_types + 1} {spec.mu_el / 2:.8g} 1.0")
    deck = f"""# Oscillatory shear of an oxidatively crosslinked fibre network -> G', G''
# generated by oxt/lammps_export.py; run: lmp -in {name}.in
units           lj
dimension       2
boundary        p p p
atom_style      molecular
read_data       {name}.data
bond_style      harmonic
{chr(10).join(coeffs)}
angle_style     harmonic
angle_coeff     1 {spec.kappa / 2:.8g} 180.0
angle_coeff     2 {kx / 2:.8g} 60.0
special_bonds   lj/coul 0.0 1.0 1.0
pair_style      zero 1.0
pair_coeff      * *
neighbor        0.3 bin
comm_modify     cutoff 3.0
fix             2d all enforce2d
fix             gag all spring/self {spec.k_gag:.8g}
min_style       fire
minimize        0 1e-10 20000 200000
velocity        all create {temp} 4928 dist gaussian
fix             nve all nve
fix             visc all langevin {temp} {temp} {damp} 48279
variable        P equal {period}
fix             shear all deform 1 xy wiggle {gamma0 * Ly:.8g} ${{P}} remap v
compute         p all pressure NULL virial
variable        sxy equal -c_p[4]
variable        g equal xy/ly
thermo_style    custom step time v_g v_sxy pe
thermo          50
fix             out all print 10 "${{g}} ${{sxy}}" file {name}_stress.txt screen no title "gamma sigma_xy"
timestep        0.01
run             {int(cycles * period / 0.01)}
"""
    (out_dir / f"{name}.in").write_text(deck)
    return out_dir / f"{name}.in"


def fit_viscoelastic(stress_file: Path, period: float):
    """Least-squares fit of sigma(t) = G' gamma(t) + G'' gamma_dot(t)/omega over full cycles."""
    d = np.loadtxt(stress_file, skiprows=1)
    g, s = d[:, 0], d[:, 1]
    w = 2 * math.pi / period
    n = len(g)
    half = n // 5  # discard the first cycle transient
    g, s = g[half:], s[half:]
    gd = np.gradient(g) / w
    A = np.stack([g, gd], 1)
    (Gp, Gpp), *_ = np.linalg.lstsq(A, s, rcond=None)
    return dict(G_storage=Gp, G_loss=Gpp, tan_delta=Gpp / Gp if Gp else float("nan"))
